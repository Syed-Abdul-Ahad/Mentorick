/**
 * Get user's current timezone
 */
export const getUserTimezone = () => {
  return Intl.DateTimeFormat().resolvedOptions().timeZone;
};

/**
 * Format timezone display name
 */
export const formatTimezoneDisplay = (timezone) => {
  try {
    const formatter = new Intl.DateTimeFormat('en-US', {
      timeZone: timezone,
      timeZoneName: 'long'
    });
    
    const parts = formatter.formatToParts(new Date());
    const timeZoneName = parts.find(part => part.type === 'timeZoneName')?.value;
    
    return `${timezone.replace('_', ' ')} ${timeZoneName ? `(${timeZoneName})` : ''}`;
  } catch (error) {
    return timezone.replace('_', ' ');
  }
};

/**
 * Get timezone offset
 */
export const getTimezoneOffset = (timezone) => {
  try {
    const date = new Date();
    const utc = date.getTime() + (date.getTimezoneOffset() * 60000);
    const targetTime = new Date(utc + (getTimezoneOffsetHours(timezone) * 3600000));
    return targetTime.getTimezoneOffset() / -60;
  } catch (error) {
    return 0;
  }
};

/**
 * Get timezone offset in hours
 */
export const getTimezoneOffsetHours = (timezone) => {
  try {
    const date = new Date();
    const utcTime = date.getTime() + (date.getTimezoneOffset() * 60000);
    const localTime = new Date(utcTime).toLocaleString('en-US', { timeZone: timezone });
    const targetTime = new Date(localTime);
    const diff = targetTime.getTime() - date.getTime();
    return diff / (1000 * 60 * 60);
  } catch (error) {
    return 0;
  }
};

/**
 * Convert time to specific timezone
 */
export const convertTimeToTimezone = (time, timezone) => {
  try {
    const date = new Date();
    const [hours, minutes] = time.split(':');
    date.setHours(parseInt(hours), parseInt(minutes), 0, 0);
    
    return date.toLocaleTimeString('en-US', {
      timeZone: timezone,
      hour12: false,
      hour: '2-digit',
      minute: '2-digit'
    });
  } catch (error) {
    return time;
  }
};

/**
 * Get next 7 days from today
 */
export const getNext7Days = () => {
  const days = [];
  const today = new Date();
  
  for (let i = 0; i < 7; i++) {
    const date = new Date(today);
    date.setDate(today.getDate() + i);
    days.push(date);
  }
  
  return days;
};

/**
 * Format date for display
 */
export const formatDateForDisplay = (date) => {
  const dayName = date.toLocaleDateString('en-US', { weekday: 'long' });
  const day = date.getDate();
  const month = date.toLocaleDateString('en-US', { month: 'long' });
  
  return {
    dayName,
    dateString: `${day} - ${month}`,
    fullDate: date.toISOString().split('T')[0]
  };
};

/**
 * Check if date is today
 */
export const isToday = (date) => {
  const today = new Date();
  return date.toDateString() === today.toDateString();
};

/**
 * Generate time slots for AM/PM
 */
export const generateTimeSlots = (period) => {
  const slots = [];
  const start = period === 'AM' ? 0 : 12;
  const end = period === 'AM' ? 12 : 24;
  
  for (let hour = start; hour < end; hour++) {
    const displayHour = hour === 0 ? 12 : hour > 12 ? hour - 12 : hour;
    const displayPeriod = hour < 12 ? 'AM' : 'PM';
    slots.push({
      value: hour,
      display: `${displayHour.toString().padStart(2, '0')}:00`,
      fullDisplay: `${displayHour}:00 ${displayPeriod}`
    });
  }
  
  return slots;
};

/**
 * Format hour for display
 */
export const formatHourDisplay = (hour) => {
  if (hour === 0) return '12:00';
  if (hour <= 12) return `${hour.toString().padStart(2, '0')}:00`;
  return `${(hour - 12).toString().padStart(2, '0')}:00`;
};

/**
 * Get period (AM/PM) for hour
 */
export const getPeriodForHour = (hour) => {
  return hour < 12 ? 'AM' : 'PM';
};